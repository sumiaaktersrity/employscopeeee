-- 1. Existing tables: auto-generate ids + add columns Week 6 needs.
-- (If a line errors with "already an identity column", skip it.)
ALTER TABLE public."CV"        ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE public."UserSkill" ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public."CV" ADD COLUMN IF NOT EXISTS "fileName" text;
ALTER TABLE public."CV" ADD COLUMN IF NOT EXISTS "filePath" text;
ALTER TABLE public."CV" ADD COLUMN IF NOT EXISTS "rawText"  text;
ALTER TABLE public."CV" ADD COLUMN IF NOT EXISTS parsed     jsonb;

-- 2. Job posts + required skills
CREATE TABLE IF NOT EXISTS public."JobPost" (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at  timestamptz NOT NULL DEFAULT now(),
  title       text NOT NULL,
  company     text NOT NULL,
  location    text,
  description text,
  "postedBy"  bigint REFERENCES public."User"(id),
  "isActive"  boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS public."JobSkill" (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "jobId"      bigint NOT NULL REFERENCES public."JobPost"(id) ON DELETE CASCADE,
  skillname    text NOT NULL,
  "isRequired" boolean NOT NULL DEFAULT true
);
CREATE INDEX IF NOT EXISTS idx_jobskill_job ON public."JobSkill"("jobId");

-- 3. Saved analysis per CV
CREATE TABLE IF NOT EXISTS public."CVAnalysis" (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at        timestamptz NOT NULL DEFAULT now(),
  "cvId"            bigint NOT NULL UNIQUE REFERENCES public."CV"(id) ON DELETE CASCADE,
  "userId"          bigint REFERENCES public."User"(id),
  score             int NOT NULL DEFAULT 0,
  "matchedSkills"   jsonb NOT NULL DEFAULT '[]',
  "missingSkills"   jsonb NOT NULL DEFAULT '[]',
  "suggestedSkills" jsonb NOT NULL DEFAULT '[]',
  suggestions       jsonb NOT NULL DEFAULT '[]',
  "totalYears"      numeric NOT NULL DEFAULT 0
);

-- 4. Private storage bucket for CV files (backend uses service role)
INSERT INTO storage.buckets (id, name, public) VALUES ('cvs', 'cvs', false)
ON CONFLICT (id) DO NOTHING;

-- 5. Block the anon key; the Express backend uses the service role.
ALTER TABLE public."JobPost"    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."JobSkill"   ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."CVAnalysis" ENABLE ROW LEVEL SECURITY;
